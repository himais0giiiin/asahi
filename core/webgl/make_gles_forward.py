#!/usr/bin/env python3
"""writes yozora_gles_forward.inc: one GL_* entry point of ANGLE for every declaration in the ES 2.0, 3.0 and extension headers that
yozora_gles.cpp does not define by hand. each entry calls the function of the system driver with the same name minus the prefix (glFoo for
GL_Foo), found once with yozora_gl_proc. a function the driver does not have raises INVALID_OPERATION and returns zero, which is what a context
without the extension does for a call that WebGL never makes, since the extension is not advertised"""
import re
import sys
from pathlib import Path

HEADERS = ["entry_points_gles_2_0_autogen.h", "entry_points_gles_3_0_autogen.h", "entry_points_gles_ext_autogen.h"]
PROTOTYPE = re.compile(r"ANGLE_EXPORT\s+([^;(]+?)\s*GL_APIENTRY\s+(GL_\w+)\s*\(([^)]*)\)\s*;", re.S)


def split_parameters(text):
    text = " ".join(text.split())
    if text in ("", "void"):
        return []
    return [part.strip() for part in text.split(",")]


def parameter_name(parameter):
    match = re.search(r"(\w+)\s*(\[\s*\d*\s*\])?$", parameter)
    if not match:
        raise SystemExit(f"yozora: cannot read the parameter {parameter!r}")
    return match.group(1)


def main():
    if len(sys.argv) != 4:
        raise SystemExit("usage: make_gles_forward.py ANGLE_ENTRY_POINT_DIR OVERRIDES_FILE OUTPUT")
    directory, overrides_path, output = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    overrides = set(re.findall(r"^\s*(?:extern \"C\" )?(?:[\w\s\*]+?)\bGL_APIENTRY\s+(GL_\w+)\s*\(", overrides_path.read_text(), re.M))
    seen = set()
    lines = ["// generated by make_gles_forward.py, do not edit"]
    for name in HEADERS:
        text = (directory / name).read_text()
        for returns, function, parameters in PROTOTYPE.findall(text):
            if function in overrides or function in seen:
                continue
            seen.add(function)
            params = split_parameters(parameters)
            names = [parameter_name(parameter) for parameter in params]
            returns = " ".join(returns.split())
            # the bounds of a Robust entry point are checked by the caller of the context, the driver takes the plain call
            robust = function.endswith("RobustANGLE")
            base = function[3:-len("RobustANGLE")] if robust else function[3:]
            drop = {"bufSize", "paramCount", "length", "columns", "rows"} if robust else set()
            # glGetInternalformativ itself takes the output capacity, unlike other robust getters
            if function == "GL_GetInternalformativRobustANGLE":
                drop.remove("paramCount")
            kept = [(parameter, name) for parameter, name in zip(params, names) if name not in drop]
            signature = ", ".join(parameter for parameter, _ in kept) or "void"
            arguments = ", ".join(name for _, name in kept)
            # the same call under the names a driver may give it: the extension of ANGLE is core in ES 3.0 or an extension of Apple, Ext or OES
            stem = re.sub(r"(ANGLE|EXT|OES|KHR|NV|CHROMIUM)$", "", base)
            # ES 3.0 core has the plain name. an ES 2.0 context has the extension ANGLE took the name from,
            # never the core one, the driver may export it for a context that cannot use it
            def unique(names):
                return list(dict.fromkeys(names))
            es3 = unique(["gl" + stem, "gl" + base, "gl" + stem + "APPLE", "gl" + stem + "EXT", "gl" + stem + "OES"])
            es2 = unique(["gl" + base, "gl" + stem + "APPLE", "gl" + stem + "EXT", "gl" + stem + "OES"])
            list_text = "{ " + ", ".join(f'"{name}"' for name in es3) + " }, { " + ", ".join(f'"{name}"' for name in es2) + " }"
            lines.append(f"ANGLE_EXPORT {returns} GL_APIENTRY {function}({', '.join('[[maybe_unused]] ' + parameter for parameter in params) if params else 'void'})")
            lines.append("{")
            lines.append(f"    using Function = {returns} (GL_APIENTRY *)({signature});")
            lines.append("    // the entry of each version of context is looked up once")
            lines.append("    static Function cached[2];")
            lines.append("    Function& function = cached[yozora_gl_slot()];")
            lines.append(f"    if (!function)")
            lines.append(f"        function = reinterpret_cast<Function>(yozora_gl_proc_any({list_text}));")
            if returns == "void":
                lines.append("    if (!function) { yozora_gl_raise(GL_INVALID_OPERATION); return; }")
                lines.append(f"    function({arguments});")
                lines.append(f'    yozora_gl_trace("{function}");')
            else:
                lines.append("    if (!function) { yozora_gl_raise(GL_INVALID_OPERATION); return {}; }")
                lines.append(f"    auto result = function({arguments});")
                lines.append(f'    yozora_gl_trace("{function}");')
                lines.append("    return result;")
            lines.append("}")
    output.write_text("\n".join(lines) + "\n")
    print(f"yozora: {len(seen)} forwarded entry points, {len(overrides)} written by hand")


if __name__ == "__main__":
    main()
